export type IconName = keyof typeof ICONS;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];

type IconProps = {
  name: IconName;
  /** Taille en px. Aligne-la sur la taille du texte adjacent. */
  size?: number;
  className?: string;
  /**
   * Libellé accessible. Sans lui l'icône est décorative et masquée aux
   * technologies d'assistance — ce qui est le bon défaut quand un texte
   * l'accompagne déjà.
   */
  label?: string;
  strokeWidth?: number;
};

export default function Icon({ name, size = 20, className, label, strokeWidth = 1.6 }: IconProps) {
  const shape = ICONS[name] as IconShape;

  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      // L'icône suit la taille du texte plutôt que d'imposer la sienne.
      style={{ flexShrink: 0 }}
    >
      {label ? <title>{label}</title> : null}
      {shape.map((entry, index) => {
        const path = typeof entry === 'string' ? { d: entry } : entry;
        return (
          <path
            key={index}
            d={path.d}
            fill={path.fill ? 'currentColor' : undefined}
            stroke={path.fill ? 'none' : undefined}
          />
        );
      })}
    </svg>
  );
}
